'use strict';
// Audit the installed pnpm lockfile graph without executing dependency code.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const lock=fs.readFileSync(path.join(root,'pnpm-lock.yaml'),'utf8');
const packageSection=lock.split('\npackages:\n')[1]?.split('\nsnapshots:\n')[0];
if(!packageSection)throw Error('LOCKFILE_PACKAGES_MISSING');
const expected=[...packageSection.matchAll(/^  (?:'([^']+)'|([^\s]+)):\s*$/gm)].map(m=>m[1]||m[2]);
const allowed=new Set(['MIT','MIT-0','ISC','BSD-2-Clause','BSD-3-Clause']);
const packages=new Map();
function collect(dir){
 for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
  if(entry.name.startsWith('.'))continue;
  const candidate=path.join(dir,entry.name);
  if(entry.name.startsWith('@')){collect(candidate);continue;}
  const manifest=path.join(candidate,'package.json');
  if(!fs.existsSync(manifest))continue;
  const real=fs.realpathSync(candidate),p=JSON.parse(fs.readFileSync(manifest,'utf8'));
  packages.set(p.name+'@'+p.version,{p,real});
 }
}
const virtualStore=path.join(root,'node_modules','.pnpm');
for(const entry of fs.readdirSync(virtualStore)){
 const dir=path.join(virtualStore,entry,'node_modules');
 if(fs.existsSync(dir)&&fs.statSync(dir).isDirectory())collect(dir);
}
const actual=[...packages.keys()].sort();
if(JSON.stringify(actual)!==JSON.stringify(expected.sort()))throw Error('INSTALLED_GRAPH_DIFFERS_FROM_LOCKFILE: run pnpm install --frozen-lockfile --ignore-scripts');
const records=[],notices=['# Locked npm dependency licenses\n\nGenerated by scripts/audit-licenses.cjs. Do not remove copyright notices.\n'];
for(const id of actual){
 const {p,real}=packages.get(id);
 const selectedLicense=p.name==='@zone-eu/mailsplit'&&p.license==='(MIT OR EUPL-1.1+)'?'MIT':p.license;
 if(!allowed.has(selectedLicense))throw Error('LICENSE_REVIEW_REQUIRED: '+id+' '+p.license);
 const names=fs.readdirSync(real).filter(name=>/^(licen[cs]e|copying|notice)([._-].*)?$/i.test(name)&&fs.statSync(path.join(real,name)).isFile()).sort();
 if(!names.length)throw Error('LICENSE_TEXT_MISSING: '+id);
 const repository=typeof p.repository==='string'?p.repository:p.repository?.url||null;
 const files=names.map(name=>{const bytes=fs.readFileSync(path.join(real,name));notices.push('\n---\n\n## '+id+' / '+name+'\n\n'+bytes.toString('utf8').replace(/\r\n/g,'\n').replace(/[ \t]+$/gm,'').trimEnd()+'\n');return {file:name,sha256:hash(bytes)};});
 records.push({name:p.name,version:p.version,declaredLicense:p.license,selectedLicense,source:'https://www.npmjs.com/package/'+p.name+'/v/'+p.version,repository,licenseFiles:files});
}
const inventory={lockfile:'pnpm-lock.yaml',lockfileSha256:hash(Buffer.from(lock)),packageCount:records.length,packages:records};
const outputs={'docs/third-party/dependencies.json':JSON.stringify(inventory,null,2)+'\n','docs/third-party/npm-licenses.txt':notices.join('')};
for(const [name,content] of Object.entries(outputs)){
 const file=path.join(root,name);
 if(process.argv.includes('--check')){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content)throw Error('LICENSE_REPORT_OUTDATED: '+name);}
 else{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content);}
}
console.log('Verified '+records.length+' locked packages; license texts retained; @zone-eu/mailsplit uses its MIT option.');
